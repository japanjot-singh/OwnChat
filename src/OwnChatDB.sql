CONTACT_NAME VARCHAR(20),CONTACT_IP VARCHAR2(20),TIMES TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY(USERNAME,CONTACT_NAME,CONTACT_IP));

